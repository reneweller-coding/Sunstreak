const CountryInfo &countryInfo( const char *country )
{
    if( !country ) return Default;
    for( const CountryInfo &c : Countries )
        if( std::strcmp( c.m_name, country ) == 0 ) return c;
    return Default;
}

int countryIndex( const char *country )
{
    if( !country ) return -1;
    for( size_t i = 0; i < std::size( Countries ); ++i )
        if( std::strcmp( Countries[i].m_name, country ) == 0 ) return static_cast<int>( i );
    return -1;
}

int countryTableSize()
{
    return static_cast<int>( std::size( Countries ) );
}

const CountryInfo &countryAt( int index )
{
    return index >= 0 && index < countryTableSize() ? Countries[index] : Default;
}

